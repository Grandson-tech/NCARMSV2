import { createReportEmptyState } from './report-empty-state.js';

const COLUMNS = Object.freeze(['Report', 'Generated By', 'Generated On', 'Format', 'Actions']);

export function createReportHistoryTable() {
  const wrapper = document.createElement('div');
  wrapper.className = 'overflow-x-auto rounded-lg border border-slate-200 bg-white';
  const table = document.createElement('table');
  table.className = 'min-w-full border-collapse';
  const caption = document.createElement('caption');
  caption.className = 'sr-only';
  caption.textContent = 'Generated report history';
  const head = document.createElement('thead');
  head.className = 'bg-slate-50';
  const row = document.createElement('tr');
  COLUMNS.forEach((column) => {
    const cell = document.createElement('th');
    cell.scope = 'col';
    cell.className = 'whitespace-nowrap px-4 py-3 text-left text-xs font-semibold uppercase tracking-wide text-slate-600';
    cell.textContent = column;
    row.append(cell);
  });
  head.append(row);
  const body = document.createElement('tbody');
  body.id = 'report-history-table-body';
  body.className = 'divide-y divide-slate-200';
  table.append(caption, head, body);
  wrapper.append(table);
  return wrapper;
}

export function renderReportHistoryEmpty(tableBody) {
  const row = document.createElement('tr');
  const cell = document.createElement('td');
  cell.colSpan = COLUMNS.length;
  cell.className = 'px-4 py-3';
  cell.append(createReportEmptyState());
  row.append(cell);
  tableBody.replaceChildren(row);
}
